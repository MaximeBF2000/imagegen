'use client';

import * as Dialog from '@radix-ui/react-dialog';
import { Check, Copy, ExternalLink, X } from 'lucide-react';
import { useState } from 'react';
import { API_URL } from '@/lib/api';
import { useConfig } from '@/lib/queries';
import { useUi } from '@/lib/store';
import { cn, copyText } from '@/lib/utils';
import { Button } from './ui/primitives';

const TABS = ['Generate', 'Batch', 'Image input', 'Inpaint', 'Watch'] as const;

function examples(base: string, auth: string) {
  const h = auth ? `\n  -H "Authorization: Bearer $IMAGEGEN_TOKEN" \\` : '';
  return {
    Generate: `# Queue 4 variants (returns immediately)
curl -X POST ${base}/api/generations \\${h}
  -H "Content-Type: application/json" \\
  -d '{
    "prompt": "a cozy cabin in a snowy forest at dusk",
    "count": 4,
    "aspectRatio": "16:9",
    "enhance": true
  }'

# Block until done (long-poll, up to 300s)
curl ${base}/api/generations/<id>/wait?timeout=120`,
    Batch: `# Queue many prompts at once — e.g. generated by a script or an LLM
curl -X POST ${base}/api/generations/bulk \\${h}
  -H "Content-Type: application/json" \\
  -d '{
    "items": [
      { "prompt": "product shot of a ceramic mug, studio light", "count": 2, "label": "catalog" },
      { "prompt": "same mug on a wooden table, morning sun", "count": 2, "label": "catalog" },
      { "prompt": "the mug in a cozy cafe scene", "enhance": true, "label": "catalog" }
    ]
  }'

# Later: list everything from that batch
curl "${base}/api/generations?label=catalog&limit=100"`,
    'Image input': `# 1) Upload (multipart) → returns [{ id, url, ... }]
curl -X POST ${base}/api/assets \\${h}
  -F "files=@photo.jpg"

# 2) Image-to-image with up to 4 references
curl -X POST ${base}/api/generations \\${h}
  -H "Content-Type: application/json" \\
  -d '{ "prompt": "turn this into a watercolor painting", "inputImageIds": ["<asset-id>"] }'

# Or inline: data URLs, base64 or http(s) URLs are uploaded for you
  -d '{ "prompt": "...", "inputImages": ["https://example.com/photo.jpg"] }'`,
    Inpaint: `# Mask: same size as the image, white = repaint, black = keep
curl -X POST ${base}/api/generations \\${h}
  -H "Content-Type: application/json" \\
  -d '{
    "prompt": "a red vintage bicycle",
    "inputImageIds": ["<image-asset-id>"],
    "mask": "data:image/png;base64,iVBORw0KGgo...",
    "count": 2
  }'`,
    Watch: `# Live updates (Server-Sent Events): generation / generation.deleted / queue
curl -N ${base}/api/events

# JavaScript
const es = new EventSource("${base}/api/events");
es.addEventListener("generation", (e) => {
  const gen = JSON.parse(e.data);
  if (gen.status === "completed") gen.jobs.forEach(j => console.log(j.image?.url));
});`,
  } satisfies Record<(typeof TABS)[number], string>;
}

export function ApiDialog() {
  const open = useUi((s) => s.apiDialogOpen);
  const setOpen = useUi((s) => s.setApiDialogOpen);
  const { data: config } = useConfig();
  const [tab, setTab] = useState<(typeof TABS)[number]>('Generate');
  const [copied, setCopied] = useState(false);
  const code = examples(API_URL, config?.authRequired ? 'yes' : '')[tab];

  return (
    <Dialog.Root open={open} onOpenChange={setOpen}>
      <Dialog.Portal>
        <Dialog.Overlay className="fixed inset-0 z-50 bg-black/70 backdrop-blur-sm animate-fade-in" />
        <Dialog.Content
          aria-describedby={undefined}
          className="fixed left-1/2 top-1/2 z-50 flex max-h-[90dvh] w-[min(760px,calc(100vw-24px))] -translate-x-1/2 -translate-y-1/2 flex-col overflow-hidden rounded-2xl border border-line-strong bg-surface shadow-2xl outline-none animate-pop"
        >
          <div className="flex items-start gap-4 border-b border-line p-5">
            <div className="flex-1">
              <Dialog.Title className="text-base font-semibold">Automate with the API</Dialog.Title>
              <p className="mt-1 text-sm text-muted">
                Everything in the studio is available over HTTP. Jobs are queued and processed in the background; new images appear here live.
              </p>
            </div>
            <Dialog.Close asChild>
              <Button variant="ghost" size="icon-sm" aria-label="Close">
                <X className="h-4 w-4" />
              </Button>
            </Dialog.Close>
          </div>
          <div className="flex gap-1 overflow-x-auto border-b border-line px-4 pt-2">
            {TABS.map((t) => (
              <button
                key={t}
                onClick={() => setTab(t)}
                className={cn(
                  '-mb-px whitespace-nowrap border-b-2 px-3 py-2 text-[13px] font-medium transition-colors',
                  t === tab ? 'border-accent text-fg' : 'border-transparent text-subtle hover:text-fg',
                )}
              >
                {t}
              </button>
            ))}
          </div>
          <div className="relative min-h-0 flex-1 overflow-auto bg-bg/60">
            <button
              onClick={async () => {
                if (await copyText(code)) {
                  setCopied(true);
                  setTimeout(() => setCopied(false), 1200);
                }
              }}
              className="absolute right-3 top-3 flex h-7 items-center gap-1 rounded-md border border-line-strong bg-surface-2 px-2 text-xs text-muted hover:text-fg"
            >
              {copied ? <Check className="h-3.5 w-3.5 text-success" /> : <Copy className="h-3.5 w-3.5" />}
              {copied ? 'Copied' : 'Copy'}
            </button>
            <pre className="p-5 pr-24 font-mono text-[12.5px] leading-relaxed text-fg/85">{code}</pre>
          </div>
          <div className="flex flex-wrap items-center justify-between gap-2 border-t border-line p-4 text-xs text-muted">
            <span>
              Base URL <code className="rounded bg-white/5 px-1.5 py-0.5 text-fg">{API_URL}/api</code>
              {config?.authRequired && ' · Bearer token required'}
            </span>
            <div className="flex gap-2">
              <a href={`${API_URL}/api/openapi.json`} target="_blank" rel="noreferrer">
                <Button size="sm" variant="ghost">
                  OpenAPI JSON
                </Button>
              </a>
              <a href={`${API_URL}/api/docs`} target="_blank" rel="noreferrer">
                <Button size="sm" variant="primary">
                  Interactive docs <ExternalLink className="h-3.5 w-3.5" />
                </Button>
              </a>
            </div>
          </div>
        </Dialog.Content>
      </Dialog.Portal>
    </Dialog.Root>
  );
}
